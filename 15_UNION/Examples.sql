-- Example 1
-- Combine player names from PLAYERS and coach names from COACHES.

SELECT PLAYER_NAME AS PERSON_NAME
FROM PLAYERS

UNION

SELECT COACH_NAME AS PERSON_NAME
FROM COACHES

GO


-- Example 2
-- Combine player names and coach names without removing duplicates.

SELECT PLAYER_NAME AS PERSON_NAME
FROM PLAYERS

UNION ALL

SELECT COACH_NAME AS PERSON_NAME
FROM COACHES

GO


-- Example 3
-- Combine players from two different positions.

SELECT PLAYER_NAME,
        POSITION
FROM PLAYERS
WHERE POSITION = 'Forward'

UNION

SELECT PLAYER_NAME,
        POSITION
FROM PLAYERS
WHERE POSITION = 'Midfielder'

GO


-- Example 4
-- Combine players from two different clubs.

SELECT PLAYER_NAME,
        CLUB_ID
FROM PLAYERS
WHERE CLUB_ID = 1

UNION

SELECT PLAYER_NAME,
        CLUB_ID
FROM PLAYERS
WHERE CLUB_ID = 2

GO


-- Example 5
-- Combine players from two countries.

SELECT PLAYER_NAME,
        COUNTRY_ID
FROM PLAYERS
WHERE COUNTRY_ID = 1

UNION ALL

SELECT PLAYER_NAME,
        COUNTRY_ID
FROM PLAYERS
WHERE COUNTRY_ID = 2

GO


-- Example 6
-- Sort the final UNION result.

SELECT PLAYER_NAME AS PERSON_NAME
FROM PLAYERS

UNION

SELECT COACH_NAME AS PERSON_NAME
FROM COACHES

ORDER BY PERSON_NAME

GO


-- Example 7
-- Use JOIN inside each SELECT.

SELECT PLAYER_NAME,
        COUNTRY_NAME
FROM PLAYERS PL
INNER JOIN COUNTRIES CT
        ON PL.COUNTRY_ID = CT.COUNTRY_ID
WHERE CT.COUNTRY_ID = 1

UNION

SELECT PLAYER_NAME,
        COUNTRY_NAME
FROM PLAYERS PL
INNER JOIN COUNTRIES CT
        ON PL.COUNTRY_ID = CT.COUNTRY_ID
WHERE CT.COUNTRY_ID = 2

GO


-- Example 8
-- Compare UNION and UNION ALL.

SELECT CLUB_ID
FROM PLAYERS

UNION

SELECT CLUB_ID
FROM PLAYERS

GO

SELECT CLUB_ID
FROM PLAYERS

UNION ALL

SELECT CLUB_ID
FROM PLAYERS

GO