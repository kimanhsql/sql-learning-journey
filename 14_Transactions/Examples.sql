-- Example 1
-- Basic Transaction

BEGIN TRANSACTION

UPDATE PLAYER
SET JERSEY_NUMBER = 10
WHERE PLAYER_ID = 1

COMMIT TRANSACTION


-- Example 2
-- Rollback Transaction

BEGIN TRANSACTION

UPDATE PLAYER
SET JERSEY_NUMBER = 10
WHERE PLAYER_ID = 1

ROLLBACK TRANSACTION


-- Example 3
-- Multiple Operations

BEGIN TRANSACTION

UPDATE PLAYER
SET JERSEY_NUMBER = 10
WHERE PLAYER_ID = 1

UPDATE PLAYER
SET JERSEY_NUMBER = 11
WHERE PLAYER_ID = 2

COMMIT TRANSACTION


-- Example 4
-- Rollback Multiple Operations

BEGIN TRANSACTION

UPDATE PLAYER
SET JERSEY_NUMBER = 10
WHERE PLAYER_ID = 1

DELETE FROM PLAYER
WHERE PLAYER_ID = 2

ROLLBACK TRANSACTION


-- Example 5
-- Savepoint

BEGIN TRANSACTION

UPDATE PLAYER
SET JERSEY_NUMBER = 10
WHERE PLAYER_ID = 1

SAVE TRANSACTION PlayerUpdate

UPDATE PLAYER
SET JERSEY_NUMBER = 11
WHERE PLAYER_ID = 2

ROLLBACK TRANSACTION PlayerUpdate

COMMIT TRANSACTION


-- Example 6
-- Transaction with TRY...CATCH

BEGIN TRY

    BEGIN TRANSACTION

    UPDATE PLAYER
    SET JERSEY_NUMBER = 10
    WHERE PLAYER_ID = 1

    COMMIT TRANSACTION

END TRY
BEGIN CATCH
    ROLLBACK TRANSACTION
END CATCH


-- Example 7
-- Transaction with INSERT

BEGIN TRANSACTION

INSERT INTO PLAYER
(
    PLAYER_NAME,
    JERSEY_NUMBER
)
VALUES
(
    'Player A',
    10
)

COMMIT TRANSACTION


-- Example 8
-- Transaction with DELETE

BEGIN TRANSACTION

DELETE FROM PLAYER
WHERE PLAYER_ID = 10

COMMIT TRANSACTION